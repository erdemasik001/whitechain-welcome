// Turns the reference drawing (slab.mjs) into the contract's fixed SVG pieces and test fixtures.
//   node build-contract.mjs
// Writes contracts/src/SlabArt.sol, contracts/test/fixtures/*.svg and web/public/badge-preview.svg. Run it after any change to
// slab.mjs, then `forge test` checks that SlabRenderer still draws exactly what slab.mjs draws.
import { writeFileSync, mkdirSync } from 'node:fs';
import { drawSlab, slabSvg } from './slab.mjs';

const contracts = new URL('../contracts/', import.meta.url);

// Draw once with a marker in place of each per-badge value, then cut at the markers.
const FIELDS = ['year', 'short', 'id', 'cert', 'bars', 'addr'];
const marked = drawSlab(Object.fromEntries(FIELDS.map((k) => [k, `\u0000${k}\u0000`])));
const parts = marked.split(/\u0000(\w+)\u0000/);
const pieces = parts.filter((_, i) => i % 2 === 0);
const order = parts.filter((_, i) => i % 2 === 1);

// SlabRenderer.svg() puts the values back in this order; fail loudly if the drawing changed it.
const EXPECTED = ['year', 'short', 'id', 'cert', 'bars', 'addr', 'id'];
if (order.join() !== EXPECTED.join()) {
  throw new Error(`Value order changed to [${order}]; update SlabRenderer.svg() to match.`);
}

const literal = (text) => {
  if (/['\\\n]/.test(text)) throw new Error('Piece contains a quote, backslash or newline');
  return (/[^\x20-\x7e]/.test(text) ? 'unicode' : '') + `'${text}'`;
};
// Same layout forge fmt uses: one line when it fits in 120 columns.
const constant = (name, value) => {
  const line = `    string internal constant ${name} = ${value};`;
  return [...line].length <= 120 ? line : `    string internal constant ${name} =\n        ${value};`;
};
const sol = `// SPDX-License-Identifier: MIT
pragma solidity 0.8.28;

// GENERATED by design/build-contract.mjs from design/slab.mjs. Do not edit by hand.

/// @notice The fixed parts of the slab badge SVG. SlabRenderer puts the per-badge values between
///         them, in this order: ${EXPECTED.map((k, i) => `P${i} ${k}`).join(', ')}, P${EXPECTED.length}.
library SlabArt {
${pieces.map((p, i) => constant(`P${i}`, literal(p))).join('\n')}
}
`;
writeFileSync(new URL('src/SlabArt.sol', contracts), sol);

// Sample badges the Solidity tests must reproduce byte for byte.
const fixtures = {
  'slab-basic': { tokenId: 1, firstContract: '0x6d1A36885424c41FaCdA6A51b47Fcdf1e1EF9901', claimedAt: 1793620429 },
  'slab-long-id-zero-address': { tokenId: 123456789, firstContract: '0x0000000000000000000000000000000000000000', claimedAt: 1798761599 },
  'slab-wide-barcode-new-year': { tokenId: 42, firstContract: '0xFFfFfFffFFfffFFfFFfFFFFFffFFFffffFfFFFfF', claimedAt: 1798761600 },
  'slab-leap-day': { tokenId: 1000, firstContract: '0x1804c8AB1F12E6bbf3894d4083f33e07309d1f38', claimedAt: 1709164800 },
};
mkdirSync(new URL('test/fixtures/', contracts), { recursive: true });
for (const [name, input] of Object.entries(fixtures)) {
  writeFileSync(new URL(`test/fixtures/${name}.svg`, contracts), slabSvg(input));
}
// The site shows this sample until the contract's own image has loaded.
writeFileSync(
  new URL('../web/public/badge-preview.svg', import.meta.url),
  slabSvg({ tokenId: 1, firstContract: '0x0000000000000000000000000000000000000000', claimedAt: 1793620429 }),
);

console.log(`SlabArt.sol: ${pieces.length} pieces, ${pieces.join('').length} bytes. Fixtures: ${Object.keys(fixtures).length}.`);
