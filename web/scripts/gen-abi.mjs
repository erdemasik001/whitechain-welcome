// Copies the contract ABIs from the Foundry build into src/abi.ts.
// Run after changing the contracts: (cd ../contracts && forge build) && npm run abi
import { readFileSync, writeFileSync } from 'node:fs'

const read = (path) => JSON.parse(readFileSync(new URL(path, import.meta.url))).abi
const badge = read('../../contracts/out/WelcomeToWhitechain.sol/WelcomeToWhitechain.json')
const renderer = read('../../contracts/out/IWelcomeRenderer.sol/IWelcomeRenderer.json')

writeFileSync(
  new URL('../src/abi.ts', import.meta.url),
  `// Generated by scripts/gen-abi.mjs from the Foundry build. Do not edit by hand.

export const badgeAbi = ${JSON.stringify(badge, null, 2)} as const

export const rendererAbi = ${JSON.stringify(renderer, null, 2)} as const
`,
)
console.log(`src/abi.ts: ${badge.length} badge entries, ${renderer.length} renderer entries`)
